    // ==================================================
    // 最新版確認
    // ==================================================

    private async Task RefreshUpdateStatusAsync()
    {
        YtDlpUpdateStatus =
            "(確認中...)";

        FfmpegUpdateStatus =
            "(確認中...)";

        DenoUpdateStatus =
            "(確認中...)";


        Task ytDlpTask =
            CheckYtDlpUpdateStatusAsync();

        Task ffmpegTask =
            CheckFfmpegUpdateStatusAsync();

        Task denoTask =
            CheckDenoUpdateStatusAsync();


        await Task.WhenAll(
            ytDlpTask,
            ffmpegTask,
            denoTask);
    }


    private async Task CheckYtDlpUpdateStatusAsync()
    {
        try
        {
            if (!_toolManager.IsYtDlpInstalled)
            {
                YtDlpUpdateStatus =
                    "";

                return;
            }


            string? latest =
                await _toolDownloader
                    .GetLatestYtDlpVersionAsync();


            if (string.IsNullOrWhiteSpace(latest))
            {
                YtDlpUpdateStatus =
                    "(最新版を確認できませんでした)";

                return;
            }


            YtDlpUpdateStatus =
                string.Equals(
                    YtDlpVersion?.Trim(),
                    latest.Trim(),
                    StringComparison.OrdinalIgnoreCase)
                    ? "(最新です)"
                    : $"(更新あり: {latest})";
        }
        catch
        {
            YtDlpUpdateStatus =
                "(最新版を確認できませんでした)";
        }
    }


    private async Task CheckDenoUpdateStatusAsync()
    {
        try
        {
            if (!_toolManager.IsDenoInstalled)
            {
                DenoUpdateStatus =
                    "";

                return;
            }


            string? latest =
                await _toolDownloader
                    .GetLatestDenoVersionAsync();


            if (string.IsNullOrWhiteSpace(latest))
            {
                DenoUpdateStatus =
                    "(最新版を確認できませんでした)";

                return;
            }


            string installed =
                ExtractVersionNumber(
                    DenoVersion);


            DenoUpdateStatus =
                string.Equals(
                    installed,
                    latest.Trim(),
                    StringComparison.OrdinalIgnoreCase)
                    ? "(最新です)"
                    : $"(更新あり: {latest})";
        }
        catch
        {
            DenoUpdateStatus =
                "(最新版を確認できませんでした)";
        }
    }


    // ==================================================
    // "deno 2.1.4 (release, ...)" のような文字列から
    // "2.1.4" だけを抜き出す
    // ==================================================

    private static string ExtractVersionNumber(
        string? versionOutput)
    {
        var match =
            System.Text.RegularExpressions.Regex
                .Match(
                    versionOutput ?? "",
                    @"\d+\.\d+(\.\d+)?");


        return match.Success
            ? match.Value
            : (versionOutput ?? "");
    }


    private async Task CheckFfmpegUpdateStatusAsync()
    {
        try
        {
            if (!_toolManager.IsFfmpegInstalled)
            {
                FfmpegUpdateStatus =
                    "";

                return;
            }


            DateTimeOffset? installedAt =
                await _toolDownloader
                    .GetFfmpegInstalledAtAsync();


            if (installedAt == null)
            {
                // ==================================================
                // この機能を導入する前にインストールされた
                // FFmpegには記録が無いため、判定できない。
                // 一度「更新」すれば以降は判定できるようになる。
                // ==================================================

                FfmpegUpdateStatus =
                    "(導入日時が未記録のため確認できません。" +
                    "一度更新すると以降は確認できます)";

                return;
            }


            DateTimeOffset? latestUpdatedAt =
                await _toolDownloader
                    .GetLatestFfmpegAssetUpdatedAtAsync();


            if (latestUpdatedAt == null)
            {
                FfmpegUpdateStatus =
                    "(最新版を確認できませんでした)";

                return;
            }


            // ==================================================
            // 数分程度の誤差は許容する
            // （ダウンロード完了とGitHub側の更新日時の
            //   タイミングのずれを吸収するため）
            // ==================================================

            FfmpegUpdateStatus =
                latestUpdatedAt.Value >
                installedAt.Value.AddMinutes(5)
                    ? $"(更新あり: " +
                      $"{latestUpdatedAt.Value.ToLocalTime():yyyy/MM/dd} 公開)"
                    : "(最新です)";
        }
        catch
        {
            FfmpegUpdateStatus =
                "(最新版を確認できませんでした)";
        }
    }


    // ==================================================
    // 戻る
    // ==================================================

    private void Back()
    {
        if (IsBusy)
            return;


        // ==================================================
        // ★ 重要
        //
        // 以前はここで new MainViewModel(_toolManager) して
        // いたため、設定画面を開いている間に溜まっていた
        // ダウンロードキューが毎回消えてしまっていた。
        //
        // 保存済みの設定（AppSettings.SaveAsyncで書き込み済み）を
        // 既存のMainViewModelへ再読込させるだけにすることで、
        // キューを保持したまま設定だけを反映する。
        // ==================================================

        _ = _owner.ReloadSettingsAsync();


        _navigationService
            .ShowMain(
