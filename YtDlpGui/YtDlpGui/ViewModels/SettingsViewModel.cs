    private void RaiseCommandStates()
    {
        if (SaveCommand
            is RelayCommand save)
        {
            save.RaiseCanExecuteChanged();
        }


        if (ResetCommand
            is RelayCommand reset)
        {
            reset.RaiseCanExecuteChanged();
        }


        if (BrowseCommand
            is RelayCommand browse)
        {
            browse.RaiseCanExecuteChanged();
        }


        if (UpdateYtDlpCommand
            is RelayCommand ytdlp)
        {
            ytdlp.RaiseCanExecuteChanged();
        }


        if (UpdateFfmpegCommand
            is RelayCommand ffmpeg)
        {
            ffmpeg.RaiseCanExecuteChanged();
        }


        if (UpdateDenoCommand
            is RelayCommand deno)
        {
            deno.RaiseCanExecuteChanged();
        }


        if (RefreshToolsCommand
            is RelayCommand refresh)
        {
            refresh.RaiseCanExecuteChanged();
        }


        if (BackCommand
            is RelayCommand back)
        {
            back.RaiseCanExecuteChanged();
        }
    }


