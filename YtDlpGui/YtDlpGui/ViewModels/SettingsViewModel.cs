    private async Task BrowseAsync()
    {
        try
        {
            var desktop =
                Application.Current?
                    .ApplicationLifetime
                    as Avalonia.Controls
                        .ApplicationLifetimes
                        .IClassicDesktopStyleApplicationLifetime;


            var window =
                desktop?.MainWindow;


            if (window == null)
            {
                StatusText =
                    "ウィンドウを取得できませんでした";

                return;
            }


            var result =
                await window.StorageProvider
                    .OpenFolderPickerAsync(
                        new FolderPickerOpenOptions
                        {
                            Title =
                                "デフォルト保存先を選択",

                            AllowMultiple =
                                false
                        });


            if (result.Count == 0)
                return;


            string? path =
                result[0]
                    .TryGetLocalPath();


            if (!string.IsNullOrWhiteSpace(path))
            {
                OutputDirectory =
                    path;


                StatusText =
                    "保存先を変更しました";
            }
        }
        catch (Exception ex)
        {
            StatusText =
                $"保存先選択エラー: {ex.Message}";
        }
    }


